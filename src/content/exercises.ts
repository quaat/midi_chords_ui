/** Transpose authored steps by a semitone offset, replacing prompts and chord symbols. */
export function transposeExplicitSteps(
  steps: ExplicitNotesStep[],
  semitones: number,
  relabel: { chordSymbol: string; prompt: string }[],
): ExplicitNotesStep[] {
  return steps.map((step: ExplicitNotesStep, index: number): ExplicitNotesStep => {
    const label = relabel[index];
    return {
      prompt: label ? label.prompt : step.prompt,
      chordSymbol: label ? label.chordSymbol : step.chordSymbol,
      durationBeats: step.durationBeats,
      notes: step.notes.map((n: AuthoredNote): AuthoredNote => ({ ...n, midi: n.midi + semitones })),
    };
  });
}

