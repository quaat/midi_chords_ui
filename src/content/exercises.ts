/** Step mode: waits for the answer; a 60 ms assembly window groups a staggered chord. */
export const STEP_TIMING: TimingPolicy = { mode: "step", assemblyWindowMs: 60 };

/** Timed mode used by the first timed variants (plan E14 defaults). */
export const TIMED_TIMING: TimingPolicy = { mode: "timed", onsetWindowMs: 120, countInBeats: 4, assemblyWindowMs: 60 };

const EXACT: AnswerPolicy = { kind: "exactVoicing" };
const TRIAD_ROLES: AnswerPolicy = { kind: "roles", requiredRoles: ["root", "third", "fifth"], octaveFree: true };

function note(midi: number, degree?: DegreeLabel, role?: ChordRole, hand?: Hand): AuthoredNote {
  const out: AuthoredNote = { midi };
  if (degree !== undefined) out.degree = degree;
  if (role !== undefined) out.role = role;
  if (hand !== undefined) out.hand = hand;
  return out;
}

